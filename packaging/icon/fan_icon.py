import math, sys
# Usage: python packaging/icon/fan_icon.py assets/icons
from PIL import Image, ImageDraw
# Propeller: 4 rounded offset lobes, pierced hub. Coordinates in a 64x64 square, center (32,32).
C = 32.0


def ellipse(cx, cy, a, b, rot, n=72):
    return [(cx + a * math.cos(t) * math.cos(rot) - b * math.sin(t) * math.sin(rot),
             cy + a * math.cos(t) * math.sin(rot) + b * math.sin(t) * math.cos(rot))
            for t in (2 * math.pi * i / n for i in range(n))]


def polar(r, ang):
    return C + r * math.cos(ang), C + r * math.sin(ang)


shapes = []
for k in range(4):
    base = math.radians(-80 + 90 * k)
    lx, ly = polar(16.5, base + math.radians(20))
    shapes.append(ellipse(lx, ly, 11.0, 8.6, base - math.radians(15)))  # lobe
    nx, ny = polar(8.0, base - math.radians(2))
    shapes.append(ellipse(nx, ny, 7.0, 3.4, base + math.radians(18)))  # neck to the hub
HUB, HOLE = 6.8, 2.8


def render(size):
    S = size * 16; f = S / 64
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rounded_rectangle([0, 0, S - 1, S - 1], radius=14 * f, fill=(0, 0, 0, 255))
    for shape in shapes:
        d.polygon([(x * f, y * f) for x, y in shape], fill=(255, 255, 255, 255))
    for r, col in ((HUB, (255, 255, 255, 255)), (HOLE, (0, 0, 0, 255))):
        d.ellipse([(C - r) * f, (C - r) * f, (C + r) * f, (C + r) * f], fill=col)
    return img.resize((size, size), Image.LANCZOS)


def svg():
    paths = "\n".join(
        '    <path d="M' + " L".join(f"{x:.2f} {y:.2f}" for x, y in s) + ' Z"/>' for s in shapes)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64">
  <!-- ControlAnything icon: white propeller on a black background. Generated by packaging/icon/fan_icon.py; fan.png and controlanything.ico are renders of it. -->
  <rect width="64" height="64" rx="14" fill="#000000"/>
  <g fill="#ffffff">
{paths}
    <circle cx="32" cy="32" r="{HUB}"/>
  </g>
  <circle cx="32" cy="32" r="{HOLE}" fill="#000000"/>
</svg>
'''


out = sys.argv[1]
render(64).save(f"{out}/fan.png")
render(256).save(f"{out}/controlanything.ico", sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
open(f"{out}/fan.svg", "w", encoding="utf-8", newline="\n").write(svg())
